    public function handle(): int
    {
        $baseUrl = rtrim(env('TIMEWEB_AI_BASE_URL', 'https://api.timeweb.ai/v1'), '/');
        $apiKey = env('TIMEWEB_AI_API_KEY');
        $model = env('TIMEWEB_AI_MODEL', 'dashscope/qwen3.5-flash');

        if (!$apiKey) { $this->error('Нет TIMEWEB_AI_API_KEY'); return self::FAILURE; }

        $existing = DreamSymbol::pluck('keyword')->all();
        $todo = array_values(array_diff(self::KEYWORDS, $existing));
        $this->info("Всего в списке: " . count(self::KEYWORDS) . ", уже есть: " . count($existing) . ", осталось сгенерировать: " . count($todo));

        foreach (array_chunk($todo, 30) as $n => $chunk) {
            $prompt = "Ты — сонник. Верни СТРОГО JSON-объект без markdown: ключ — слово, значение — толкование сна на русском (1-2 предложения, тёплый тон). Слова: " . implode(', ', $chunk);

            try {
                $resp = Http::timeout(120)->withHeaders([
                    'Authorization' => "Bearer {$apiKey}",
                    'Content-Type' => 'application/json',
                ])->post("{$baseUrl}/chat/completions", [
                    'model' => $model,
                    'messages' => [['role' => 'user', 'content' => $prompt]],
                    'temperature' => 0.7,
                    'max_tokens' => 3500,
                    'enable_thinking' => false,
                ]);

                if (!$resp->successful()) { $this->warn("Батч {$n}: HTTP {$resp->status()}"); continue; }

                $text = trim($resp->json('choices.0.message.content'));
                $s = strpos($text, '{'); $e = strrpos($text, '}');
                if ($s !== false && $e !== false) $text = substr($text, $s, $e - $s + 1);
                $data = json_decode($text, true);

                if (!is_array($data)) { $this->warn("Батч {$n}: JSON не распознан"); continue; }

                $saved = 0;
                foreach ($data as $kw => $interp) {
                    $kw = mb_strtolower(trim($kw));
                    if ($kw && is_string($interp) && !DreamSymbol::where('keyword', $kw)->exists()) {
                        DreamSymbol::create(['keyword' => $kw, 'interpretation' => trim($interp), 'ai_generated' => true, 'approved' => true]);
                        $saved++;
                    }
                }
                $this->info("Батч {$n}: сохранено {$saved}");
            } catch (\Throwable $e) {
                $this->warn("Батч {$n}: " . $e->getMessage());
            }
            sleep(2);
        }

        $this->info('ИТОГО в базе: ' . DreamSymbol::count());
        return self::SUCCESS;
    }
